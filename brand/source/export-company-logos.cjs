// Exports the website's logo assets:
// - each company's own logo (brand/company-logos) → public/logos/<slug>.webp,
//   plus src/content/logos.ts with their sizes;
// - the American Elite Enterprises crest (source/original-crest.png, the logo
//   of the original website) → public/brand files, favicons and apple icon.
//
//   node export-company-logos.cjs
//
// Needs sharp on NODE_PATH.
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.join(__dirname, "../..");
const LOGOS = path.join(__dirname, "../company-logos");
const CREST = path.join(__dirname, "original-crest.png");
const out = (...p) => path.join(ROOT, ...p);

// Crest centred on a square canvas; `pad` is the margin as a share of the side.
const square = async (size, pad, background = { r: 0, g: 0, b: 0, alpha: 0 }) => {
  const inner = Math.round(size * (1 - pad * 2));
  const crest = await sharp(CREST).resize({ width: inner, height: inner, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background } })
    .composite([{ input: crest, gravity: "center" }])
    .png({ compressionLevel: 9, palette: true, quality: 92, effort: 10 });
};

(async () => {
  fs.mkdirSync(out("public/logos"), { recursive: true });
  const entries = [];
  for (const file of fs.readdirSync(LOGOS).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort()) {
    const slug = file.replace(/\.[^.]+$/, "");
    // Trim flat margins, then fit a 400×200 box (shown at up to ~160×80 CSS px).
    const trimmed = await sharp(path.join(LOGOS, file)).trim({ threshold: 12 }).toBuffer().catch(() => fs.readFileSync(path.join(LOGOS, file)));
    const info = await sharp(trimmed)
      .resize({ width: 400, height: 200, fit: "inside", withoutEnlargement: true })
      .webp({ quality: 86, alphaQuality: 90 })
      .toFile(out("public/logos", `${slug}.webp`));
    entries.push([slug, info.width, info.height]);
  }
  const ts = `// Generated by brand/source/export-company-logos.cjs — do not edit by hand.
// Each company's own logo, taken from its website (sources: docs/company-logos.md).

export type Logo = { src: string; width: number; height: number };

export const logos: Record<string, Logo> = {
${entries.map(([s, w, h]) => `  "${s}": { src: "/logos/${s}.webp", width: ${w}, height: ${h} },`).join("\n")}
};
`;
  fs.writeFileSync(out("src/content/logos.ts"), ts);
  console.log(`${entries.length} company logos`);

  const crestJobs = [
    [sharp(CREST).resize({ width: 800 }).png({ compressionLevel: 9 }), "public/brand/american-elite-crest.png"],
    [sharp(CREST).resize({ width: 320 }).webp({ quality: 86, alphaQuality: 90 }), "public/brand/american-elite-crest-sm.webp"],
    [await square(32, 0), "src/app/icon1.png"],
    [await square(512, 0.02), "src/app/icon2.png"],
    [await square(180, 0.06, { r: 255, g: 255, b: 255, alpha: 1 }), "src/app/apple-icon.png"],
  ];
  for (const [img, file] of crestJobs) {
    const info = await img.toFile(out(file));
    console.log(`${file} ${info.width}x${info.height} ${Math.round(info.size / 1024)}KB`);
  }
})();
